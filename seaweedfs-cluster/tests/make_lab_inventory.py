#!/usr/bin/env python3
"""Derive a single-machine lab inventory from the production inventory.

Every production IP 10.X.Y.Z is remapped to loopback 127.X.Y.Z, so each
"host" keeps its own address and the *same* ports as production. Topology,
racks, roles, ports, security and tiering stay identical; only sizes, the
transport (local processes instead of ssh+systemd) and the edition change.

usage: make_lab_inventory.py inventory/production.yaml inventory/lab.yaml [--weed PATH]
"""
import argparse
import copy
from pathlib import Path

import yaml

ap = argparse.ArgumentParser()
ap.add_argument("src")
ap.add_argument("dst")
ap.add_argument("--weed", default=str(Path(__file__).resolve().parents[2] / "lab/bin/weed"))
ap.add_argument("--edition", default="oss")
ap.add_argument("--name", default="lab", help="lab name: build/<name>, ../lab/run-<name>")
ap.add_argument("--volume-mb", type=int, default=64)
a = ap.parse_args()

inv = yaml.safe_load(open(a.src))
lab = copy.deepcopy(inv)
g = lab["global"]
g.update({
    "edition": a.edition,
    "weed_binary": a.weed,
    "transport": "local",
    "runtime": "local",
    "path_prefix": ("../lab/run/{cluster}/{host}" if a.name == "lab" else "../lab/run-" + a.name + "/{cluster}/{host}"),
    "build_dir": "build/" + a.name,
})
g["master"]["volume_size_limit_mb"] = a.volume_mb
g["volume"]["allow_untrusted_remote_endpoints"] = True   # loopback lab: allow volume-to-volume copies
g["volume"]["volume_size_gb"] = a.volume_mb / 1000
g["workers"]["count"] = 1 if a.edition == "oss" else 2
if a.edition == "enterprise":
    # loopback-only lab: admin API without login so tests can drive tiering / Data Movement over REST
    g["security"]["admin_auth"] = False


def remap(ip):
    p = ip.split(".")
    return f"127.{p[1]}.{p[2]}.{p[3]}"


for cname, cl in lab["clusters"].items():
    cl["admin"]["ip"] = remap(cl["admin"]["ip"])
    for n in cl["nodes"]:
        n["ip"] = remap(n["ip"])
        for d in n.get("disks", []):
            d["size_gb"] = 4          # lab directories, not real disks
            d["max"] = 24             # 24 x 64MB volumes per dir
    if cl.get("role") == "standby":
        # weed 4.47 binds the admin worker-gRPC listener on ALL interfaces (fixed upstream later),
        # so two admins cannot share one lab machine on the same port. Lab-only override.
        cl["ports_override"] = {"admin": {"http": 23656}}
        # OSS stand-in for Enterprise Data Movement: continuous filer.sync on the DR admin host
        if a.edition == "oss":
            for n in cl["nodes"]:
                if "admin" in n["roles"]:
                    n["roles"].append("filer_sync")

lab["sla"] = {"rpo_seconds": 60, "rto_minutes": 15, "daily_ingest_gb": None}
Path(a.dst).write_text("# GENERATED by tests/make_lab_inventory.py from " + a.src + " - do not edit\n" +
                       yaml.safe_dump(lab, sort_keys=False, width=140))
print(f"wrote {a.dst}")
